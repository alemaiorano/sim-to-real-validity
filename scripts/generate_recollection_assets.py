"""Export newly collected results separately from unchanged historical reports."""
import hashlib
import json
from pathlib import Path
import compute_validity as cv

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "recollection/2026-10-31"
LABELS = {
    "goodman_kruskal_gamma": r"Goodman--Kruskal $\gamma$",
    "kendall_tau_b": r"Kendall $\tau_b$",
    "spearman_rho": r"Spearman $\rho$",
    "top1_accuracy": "Expected top-1",
    "bottom1_accuracy": "Expected bottom-1",
    "lift_captured": "Captured lift",
}


def cell(value, decision=False, gap=False):
    if value["mean"] is None:
        return r"\textemdash"
    scale, precision = (100, 1) if decision else (1, 3)
    suffix = (" pp" if gap else r"\%") if decision else ""
    low, high = value["ci95"]
    return (f"{value['mean'] * scale:.{precision}f}{suffix} "
            f"[{low * scale:.{precision}f}, {high * scale:.{precision}f}]")


def macro(name, value):
    return "\\newcommand{\\" + name + "}{" + str(value) + "}\n"


def main():
    provenance = json.loads((DATA / "provenance.json").read_text())
    reports = {}
    for backend in ["gemini", "azure"]:
        path = DATA / f"{backend}.json"
        if hashlib.sha256(path.read_bytes()).hexdigest() != provenance["report_sha256"][backend]:
            raise ValueError("changed recollection report: " + backend)
        report = json.loads(path.read_text())
        if report["backend"] != backend or report["plan_sha256"] != provenance["plan_sha256"]:
            raise ValueError("incompatible collection identity")
        if report["unresolved_observations"] != 0:
            raise ValueError("collection is unfinished; do not export it as the final experiment")
        reports[backend] = report
    models = {"gemini": "Gemini 3.1 Flash-Lite", "azure": "GPT-4.1"}
    tex = ["% AUTO-GENERATED by scripts/generate_recollection_assets.py\n"]
    for backend, report in reports.items():
        primary = report["primary"]
        caption = (
            f"New {models[backend]} comparison on {report['n_primary_packages']} complete packages "
            f"from the {report['n_eligible_packages']}-package selected cohort. "
            "Every retained variant has all planned observations in both arms. "
            "Counts are metric-specific valid panel/baseline/paired packages. "
            "Gap is baseline minus panel; decision gaps use percentage points. "
            "Percentile bootstrap CIs condition on this cohort and these recorded generations. "
            "Undefined coefficients are omitted with their denominators disclosed.")
        if backend == "azure":
            caption += " Azure requested three indexed choices per call; choices are not assumed independent."
        rows = []
        for key in cv.METRICS:
            panel, base = primary["panel"][key], primary["baseline"][key]
            paired = primary["paired_gap"]["metrics"][key]
            decision = key in {"top1_accuracy", "bottom1_accuracy"}
            rows.append(f"    {LABELS[key]} & {cell(panel, decision)} & {cell(base, decision)} & "
                        f"{cell(paired, decision, True)} & "
                        f"{panel['n_valid']}/{base['n_valid']}/{paired['n_paired']} " + r"\\" + "\n")
        tex += [
            "\\begin{table*}[t]\n\\centering\n",
            "\\caption{" + caption + "}\n",
            "\\label{tab:new_" + backend + "}\n\\small\n",
            "\\resizebox{\\textwidth}{!}{\\begin{tabular}{lcccc}\n\\toprule\n",
            "Metric & Panel [95\\% CI] & Baseline [95\\% CI] & Paired gap [95\\% CI] & $n_{valid}$ p/b/pair " + r"\\" + "\n\\midrule\n",
            *rows, "\\bottomrule\n\\end{tabular}}\n\\end{table*}\n",
        ]
    (ROOT / "latex/tables/recollection.tex").write_text("".join(tex))
    variables = ["% AUTO-GENERATED by scripts/generate_recollection_assets.py\n"]
    for backend, prefix in [("gemini", "newGemini"), ("azure", "newGpt")]:
        report = reports[backend]
        variables += [
            macro(prefix + "N", report["n_primary_packages"]),
            macro(prefix + "ExcludedN", len(report["excluded_primary_package_ids"])),
            macro(prefix + "PanelRankUndefinedN", report["primary"]["panel"]["kendall_tau_b"]["n_undefined"]),
            macro(prefix + "BaselineRankUndefinedN", report["primary"]["baseline"]["kendall_tau_b"]["n_undefined"]),
        ]
        for arm, suffix in [("panel", "Panel"), ("baseline", "Baseline")]:
            values = report["primary"][arm]
            for key, label, scale, precision in [
                ("kendall_tau_b", "Tau", 1, 3),
                ("goodman_kruskal_gamma", "Gamma", 1, 3),
                ("top1_accuracy", "TopOne", 100, 1),
                ("lift_captured", "Lift", 1, 3),
            ]:
                estimate = values[key]["mean"]
                number = f"{estimate * scale:.{precision}f}" if estimate is not None else "undefined"
                if scale == 100 and estimate is not None:
                    number += r"\%"
                variables.append(macro(prefix + suffix + label, number))
        for key, label, scale, precision in [
            ("kendall_tau_b", "Tau", 1, 3), ("top1_accuracy", "TopOne", 100, 1)]:
            estimate = report["primary"]["paired_gap"]["metrics"][key]
            for field, value in [("", estimate["mean"]),
                                 ("Low", estimate["ci95"][0] if estimate["ci95"] else None),
                                 ("High", estimate["ci95"][1] if estimate["ci95"] else None)]:
                number = f"{value * scale:+.{precision}f}" if value is not None else "undefined"
                variables.append(macro(prefix + "Gap" + label + field, number))
            variables.append(macro(prefix + "Paired" + label + "N", estimate["n_paired"]))
    (ROOT / "latex/recollection_variables.tex").write_text("".join(variables))
    print("Exported raw-backed recollection tables and variables.")


if __name__ == "__main__":
    main()
