#!/usr/bin/env python3
"""Export the explicitly scoped offline GPT diagnostic; never modify historical reports."""
import hashlib
import json
from pathlib import Path
from historical_results import read_historical

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "reanalysis/2026-10-31/gpt41.json"


def main():
    provenance = json.loads((SOURCE.parent / "provenance.json").read_text())
    for name, expected in provenance["artifacts_sha256"].items():
        if hashlib.sha256((SOURCE.parent / name).read_bytes()).hexdigest() != expected:
            raise ValueError("changed derivative artifact: " + name)
    for name, expected in provenance["producer_sha256"].items():
        if hashlib.sha256((ROOT / name).read_bytes()).hexdigest() != expected:
            raise ValueError("changed derivative producer: " + name)
    d = json.loads(SOURCE.read_text())
    f = json.loads((SOURCE.parent / "filter_comparison.json").read_text())
    if d["provenance"]["corpus_sha256"] != f["corpus_sha256"] or not f["corrected_ids_subset_of_legacy"]:
        raise ValueError("incompatible diagnostic populations")
    if d["n_eligible"] != f["corrected_selected"] or d["provider_calls"] != 0:
        raise ValueError("diagnostic identity mismatch")
    panel, base = d["persona_panel"], d["no_persona_baseline"]
    metrics = ["goodman_kruskal_gamma", "kendall_tau_b", "top1_accuracy"]
    labels = ["Goodman--Kruskal $\\gamma$", "Kendall $\\tau_b$", "Expected top-1"]
    def cell(x, pct=False):
        scale, suffix, precision = (100, r"\%", 1) if pct else (1, "", 3)
        return f"{x['mean']*scale:.{precision}f}{suffix} [{x['ci95'][0]*scale:.{precision}f}, {x['ci95'][1]*scale:.{precision}f}]"
    rows = []
    for key, label in zip(metrics, labels):
        gap = d["paired_gap"]["metrics"][key]
        rows.append(f"    {label} & {cell(panel[key], key == 'top1_accuracy')} & "
                    f"{cell(base[key], key == 'top1_accuracy')} & "
                    f"{cell(gap, key == 'top1_accuracy').replace(chr(92) + chr(37), ' pp')} & "
                    f"{panel[key]['n_valid']}/{base[key]['n_valid']}/{gap['n_paired']} " + r"\\" + "\n")
    tex = (r"""% AUTO-GENERATED by scripts/generate_reanalysis_assets.py
\begin{table*}[t]
\centering
\caption{GPT-4.1 scalar-checkpoint analysis on recorded post-parser values. Simultaneous winner
screen and uniform expected tie credit; marginal percentile bootstrap CIs. Gap is baseline
minus panel on paired packages; top-1 gap is in percentage points. Counts are per-metric valid
panel/baseline/paired. Original responses are unavailable, so this does not validate the
collection parser. Sampling remains 30 panel observations versus 10 baseline draws per variant.}
\label{tab:corrected_gpt}
\small
\resizebox{\textwidth}{!}{\begin{tabular}{lcccc}
\toprule
Metric & Panel [95\% CI] & Baseline [95\% CI] & Paired gap [95\% CI] & $n_{valid}$ p/b/pair \\
\midrule
""" + "".join(rows) + r"""\bottomrule
\end{tabular}}
\end{table*}
""")
    (ROOT / "latex/tables/corrected_gpt.tex").write_text(tex)
    rep = read_historical("replication.json")["reddit-titles"]
    macros = {
        "newSelectedN": str(f["corrected_selected"]),
        "legacySelectedN": str(f["legacy_selected"]),
        "correctedPanelN": str(panel["n_packages"]),
        "correctedBaseN": str(base["n_packages"]),
        "correctedPairedN": str(d["paired_gap"]["n_common_packages"]),
        "correctedPanelTau": f"{panel['kendall_tau_b']['mean']:.3f}",
        "correctedBaseTau": f"{base['kendall_tau_b']['mean']:.3f}",
        "redditPanelTop": f"{rep['persona']['top1']['mean']*100:.1f}" + r"\%",
        "redditBaseTop": f"{rep['baseline']['top1']['mean']*100:.1f}" + r"\%",
        "redditPanelLift": f"{rep['persona']['lift_captured']['mean']:.3f}",
        "redditBaseLift": f"{rep['baseline']['lift_captured']['mean']:.3f}",
    }
    (ROOT / "latex/reanalysis_variables.tex").write_text(
        "% AUTO-GENERATED by scripts/generate_reanalysis_assets.py\n" +
        "".join("\\newcommand{\\"+k+"}{"+v+"}\n" for k,v in macros.items()))
    print("Exported scoped reanalysis assets; source sha256=" + hashlib.sha256(SOURCE.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
