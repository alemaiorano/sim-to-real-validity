#!/usr/bin/env python3
"""Generate latex/tables/replication.tex from reports/replication.json: per-dataset persona vs
no-persona baseline (Goodman-Kruskal gamma, gap, lift captured). Historic reported conditions
are not independently reconstructed from raw predictions here. No hand-edited tables."""
from __future__ import annotations

import json
import sys
from pathlib import Path
from historical_results import read_historical, historical_csv

PAPER_DIR = Path(__file__).resolve().parents[1]
REPORT = PAPER_DIR / "reports" / "replication.json"
OUT = PAPER_DIR / "latex" / "tables" / "replication.tex"

LABELS = {
    "exploratory": "Upworthy exploratory (2013--15)",
    "holdout": "Upworthy holdout (2013--15)",
    "confirmatory": "Upworthy confirmatory (2013--15)",
    "mind-news": "MIND news (2019)",
    "reddit-titles": "Reddit titles (2008--12)",
}
ORDER = ["exploratory", "holdout", "confirmatory", "mind-news", "reddit-titles"]


def main() -> None:
    if not REPORT.exists():
        print(f"[rep-table][FATAL] missing {REPORT}", file=sys.stderr); sys.exit(1)
    d = read_historical(REPORT.name)
    rows = []
    for k in ORDER:
        if k not in d:
            continue
        p, b = d[k]["persona"], d[k]["baseline"]
        gap = b["goodman_kruskal_gamma"]["mean"] - p["goodman_kruskal_gamma"]["mean"]
        rows.append(f"    {LABELS[k]} & {p['n']}/{b['n']} & {p['goodman_kruskal_gamma']['mean']:.3f} "
                    f"& {b['goodman_kruskal_gamma']['mean']:.3f} & ${gap:+.3f}$ & "
                    f"{p['lift_captured']['mean']:.2f}/{b['lift_captured']['mean']:.2f} \\\\\n")
    tex = [
        "% AUTO-GENERATED by scripts/generate_replication_table.py — DO NOT EDIT BY HAND.\n",
        "\\begin{table*}[t]\n  \\centering\n",
        "  \\caption{Supplementary estimates under the top-versus-runner-up screen and first-index tie breaking. "
        "$n_{total}$ is panel/baseline coverage, not the correlation-specific valid count "
        "(unavailable). Lift is the fraction of the observed outcome-rate range captured by "
        "the selected variant (panel/baseline). The panel exceeds the baseline on Reddit lift "
        "and top-1 (discussed in text); near-zero gamma does not establish equivalence or "
        "unpredictability. Gap is the difference of reported marginal gamma means, not a paired "
        "contrast. The summary does not retain draw counts or evaluated package IDs; the "
        "exploratory row differs from Table~\\ref{tab:validity}, and protocol equivalence "
        "cannot be verified from the aggregates alone.}\n",
        "  \\label{tab:replication}\n",
        "  \\small\n",
        "  \\begin{tabular}{lccccc}\n    \\toprule\n",
        "    Dataset & $n_{total}$ p/b & Persona $\\gamma$ & Baseline $\\gamma$ & Gap & Lift p/b \\\\\n    \\midrule\n",
        *rows, "    \\bottomrule\n  \\end{tabular}\n\\end{table*}\n",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(tex))
    print(f"[rep-table] wrote {OUT}")


if __name__ == "__main__":
    main()
