"""Export all period-exclusion paired metrics, without changing primary assets."""
import hashlib
import json
from pathlib import Path
import compute_validity as cv
from generate_recollection_assets import LABELS, cell, macro

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'recollection/2026-10-31'


def main():
    source=DATA/'window_sensitivity.json'
    provenance=json.loads((DATA/'window_sensitivity.provenance.json').read_text())
    if hashlib.sha256(source.read_bytes()).hexdigest()!=provenance['report_sha256']:
        raise ValueError('changed window sensitivity report')
    d=json.loads(source.read_text())
    if d['status']!='post_hoc_sensitivity' or d['provider_calls']!=0:
        raise ValueError('not the declared offline sensitivity')
    tex=[r'''% AUTO-GENERATED by scripts/generate_window_sensitivity_assets.py
\begin{table*}[t]
\centering
\caption{Post-hoc sensitivity excluding the archive's documented randomization-risk window
(25 June 2013--10 January 2014 inclusive) from each model's complete primary cohort.
Primary reports and recorded generations remain unchanged. All six metrics are shown;
gaps are baseline minus panel, decision gaps are percentage points, and counts are metric-specific
valid pairs. Pointwise percentile bootstrap CIs condition on retained packages and generations;
remaining tests are not certified defect-free.}
\label{tab:window_sensitivity}
\small
\begin{tabular}{llcc}
\toprule
Model (complete packages) & Metric & Paired gap [95\% CI] & $n_{paired}$ \\
\midrule
''']
    variables=['% AUTO-GENERATED by scripts/generate_window_sensitivity_assets.py\n']
    for label,key in [('riskCorpusN','corpus'),('riskLegacyN','legacy_selected'),('riskSelectedN','new_selected')]:
        variables.append(macro(label,d['populations'][key]['n_in_window']))
    for backend,prefix,label in [('gemini','windowGemini','Gemini'),('azure','windowGpt','GPT-4.1')]:
        r=d['models'][backend]
        variables += [macro(prefix+'N',r['n_retained']),macro(prefix+'ExcludedN',len(r['excluded_window_package_ids']))]
        for metric in cv.METRICS:
            value=r['paired_gap']['metrics'][metric]
            decision=metric in ['top1_accuracy','bottom1_accuracy']
            tex.append(f"{label} ({r['n_retained']}) & {LABELS[metric]} & {cell(value,decision,True)} & {value['n_paired']} "+r'\\'+'\n')
        if backend=='gemini':tex.append('\\midrule\n')
        for metric,name,scale,precision in [('kendall_tau_b','Tau',1,3),('top1_accuracy','TopOne',100,1)]:
            value=r['paired_gap']['metrics'][metric]
            for field,num in [('',value['mean']),('Low',value['ci95'][0]),('High',value['ci95'][1])]:
                variables.append(macro(prefix+'Gap'+name+field,f'{num*scale:+.{precision}f}'))
            variables.append(macro(prefix+'Paired'+name+'N',value['n_paired']))
    tex.append('\\bottomrule\n\\end{tabular}\n\\end{table*}\n')
    (ROOT/'latex/tables/window_sensitivity.tex').write_text(''.join(tex))
    (ROOT/'latex/window_sensitivity_variables.tex').write_text(''.join(variables))
    print('Exported complete six-metric period sensitivity and source-backed macros.')


if __name__=='__main__':main()
