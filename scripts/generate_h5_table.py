#!/usr/bin/env python3
"""Generate latex/tables/h5_aggregation.tex (tab:h5agg) from reports/h5_aggregation.csv.

Robustness of the persona-panel result to the aggregation rule (H5): six rules applied to the
SAME per-persona observations, with the no-persona baseline as reference. No hand-edited tables;
re-running on an unchanged CSV yields a byte-stable file. Run analyze_h5_aggregation.py first.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path
from historical_results import read_historical, historical_csv

PAPER_DIR = Path(__file__).resolve().parents[1]
SRC = PAPER_DIR / "reports" / "h5_aggregation.csv"
OUT = PAPER_DIR / "latex" / "tables" / "h5_aggregation.tex"

LABEL = {
    "baseline_no_persona": "No-persona baseline",
    "mean": "Equal-persona mean",
    "median": "Panel median",
    "trimmed20": "Trimmed mean (20\\%)",
    "zmean": "Per-persona $z$-mean",
    "borda": "Borda (rank fusion)",
    "condorcet": "Condorcet (pairwise)",
}
ORDER = ["baseline_no_persona", "mean", "median", "trimmed20", "zmean", "borda", "condorcet"]


def main() -> None:
    if not SRC.exists():
        sys.exit(f"[table][FATAL] {SRC} missing; run scripts/analyze_h5_aggregation.py first")
    rows = {r["rule"]: r for r in historical_csv(SRC.name)}
    n = rows["mean"]["n"]

    body = []
    for rule in ORDER:
        r = rows[rule]
        tau = f"{float(r['goodman_kruskal_gamma']):.3f} [{float(r['gamma_lo']):.3f}, {float(r['gamma_hi']):.3f}]"
        t1 = f"{float(r['top1'])*100:.1f}\\% [{float(r['top1_lo'])*100:.1f}, {float(r['top1_hi'])*100:.1f}]"
        line = f"    {LABEL[rule]} & {tau} & {t1} \\\\\n"
        if rule == "baseline_no_persona":
            line += "    \\midrule\n"
        body.append(line)

    caption = (
        f"Historical H5 aggregation comparison ($n_{{total}}={n}$ for panel rules). "
        "The baseline has 398 covered packages; correlation-specific valid counts are "
        "unavailable. The mean row weights draw-collapsed personas equally, whereas the "
        "primary collector weights recorded observations equally. These estimands can "
        "differ when draws are missing; the stored reports do not identify the cause of "
        "their top-1 discrepancy. No tested rule reaches the baseline's reported gamma. "
        "This descriptive comparison does not identify a failure mechanism. "
        "Legacy screen, first-index tie breaking, 95\\% marginal bootstrap CIs.")

    tex = [
        "% AUTO-GENERATED by scripts/generate_h5_table.py — DO NOT EDIT BY HAND.\n",
        "\\begin{table}[t]\n  \\centering\n",
        f"  \\caption{{{caption}}}\n  \\label{{tab:h5agg}}\n",
        "  \\small\n  \\resizebox{\\columnwidth}{!}{%\n  \\begin{tabular}{lcc}\n    \\toprule\n",
        "    Aggregation & Goodman--Kruskal $\\gamma$ [95\\% CI] & Top-1 [95\\% CI] \\\\\n",
        "    \\midrule\n", *body, "    \\bottomrule\n  \\end{tabular}}\n\\end{table}\n",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(tex))
    print(f"[table] wrote {OUT}")


if __name__ == "__main__":
    main()
